// Generates src/core/ff3nes/tables.ts (item, job and spell names for Final Fantasy III on the Famicom, as the English fan
// translation names them) from everything8215's disassembly. Run only when you want to regenerate the tables:
//
//   git clone --depth 1 https://github.com/everything8215/ff3 /tmp/ff3
//   node scripts/gen-ff3nes-data.mjs /tmp/ff3
//
// ff3u-text.txt is the translation's string table: string 0x400 + n is the name of item id n, string 0x1E2 + n the name
// of job n. Weapon and armor names start with an icon (\sword, \helm, ...) that the game draws in front of a short name;
// here the icon becomes a word after the name ("Long" + sword = "Long Sword") unless the name already says what it is.
// The dump leaves out a few words the translation keeps in a dictionary; FILL has them, read off the game's own screens.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const src = process.argv[2] && resolve(process.argv[2]);
if (!src) { console.error('Usage: node scripts/gen-ff3nes-data.mjs <path to the ff3 disassembly>'); process.exit(1); }

const strings = new Map();
for (const line of readFileSync(join(src, 'ff3u-text.txt'), 'utf8').split(/\r?\n/)) {
  const m = line.match(/^0x([0-9A-F]{4}): ?(.*)$/);
  if (m) strings.set(parseInt(m[1], 16), m[2]);
}

const FILL = {
  0x03: 'Dragon', 0x0a: 'Flame', 0x16: 'Thor', 0x1a: 'Thunder', 0x42: 'Blizzard', 0x48: 'Lamia', 0x55: 'Medusa',
  0xa7: 'HiPotion', 0xcf: 'Quake', 0xda: 'Soft', 0xdc: 'Odin', 0xe3: 'Titan', 0xea: 'Ifrit', 0xf1: 'Ramuh', 0xf8: 'Shiva',
};
const NOUN = {
  claw: 'Claw', nunchucks: 'Nunchuck', rod: 'Rod', staff: 'Staff', hammer: 'Hammer', axe: 'Axe', spear: 'Spear',
  knife: 'Knife', sword: 'Sword', book: 'Book', bell: 'Bell', harp: 'Harp', bow: 'Bow', arrow: 'Arrow', shield: 'Shield',
  helm: 'Helm', ring: 'Ring', glove: 'Glove', armor: 'Armor', robe: 'Armor',
};
// Names that already say what they are, so no word is added.
const WHOLE = /(Claw|Knife|Axe|Bow|Mail|Belt|Robe|Suit|Hood|band|Ribbon|Cloth|Kenpo|Gauntlet|Boomerng|FullMoon|Shuriken|Nunchuck|Tonfa|Staff|Hammer|Dagger)$/;
const DARK = new Set(['Ashura', 'Kotetsu', 'Kiku', 'Masamune']);

const ITEMS = [];
const KINDS = [];
for (let id = 0; id < 256; id++) {
  let s = (strings.get(0x400 + id) ?? '').replace(/\\lack1\\lack2/g, 'lack');
  let kind = '';
  const m = s.match(/^\\([a-z]+?|Nunchucks)(?=[A-Z0-9 ]|$)(.*)$/);
  if (m) { kind = m[1].toLowerCase(); s = m[2]; }
  s = s.trim().replace(/’/g, "'");
  if (FILL[id]) s = FILL[id];
  if (id === 0 || id === 0x57 || s === '?') s = '';
  if (kind === 'darksword' || DARK.has(s)) kind = 'katana';
  if (s && NOUN[kind] && !WHOLE.test(s)) s = `${s} ${NOUN[kind]}`;
  if (s === '3-Part Nunchuck' || s === '3-Part') s = '3-Part Nunchuck';
  ITEMS.push(s);
  KINDS.push(kind);
}
const check = { 0x24: 'Long Sword', 0x37: 'Masamune', 0xa6: 'Potion', 0xa8: 'Elixir', 0xc8: 'Flare', 0xff: 'Chocb' };
for (const [id, want] of Object.entries(check)) if (ITEMS[id] !== want) throw new Error(`item ${id}: ${ITEMS[id]}, wanted ${want}`);

const list = (a) => `[\n${a.map((s) => `  ${JSON.stringify(s)},`).join('\n')}\n]`;
const out = `// Generated by scripts/gen-ff3nes-data.mjs from everything8215's disassembly (ff3u-text.txt). Do not edit by hand.
// Final Fantasy III (Famicom) names by save id, as the English fan translation has them.

/** Every item by the id the save uses: weapons 0x01-0x56, shields 0x58-0x61, helmets 0x62-0x71, armor 0x72-0x8A,
 * gloves and rings 0x8B-0x97, key items 0x98-0xA4, items 0xA6-0xC7, spells 0xC8-0xFF. */
export const ITEMS: readonly string[] = ${list(ITEMS)};
/** The icon the game draws in front of each name: the kind of weapon or armor, or the school of a spell. */
export const ITEM_KINDS: readonly string[] = ${list(KINDS)};
`;
writeFileSync(new URL('../src/core/ff3nes/tables.ts', import.meta.url), out);
console.log('wrote src/core/ff3nes/tables.ts');
