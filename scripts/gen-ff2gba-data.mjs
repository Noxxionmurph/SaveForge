// Generates src/core/ff2gba/tables.ts for Final Fantasy II in Dawn of Souls (GBA, US, game code BFFE).
//
//   node scripts/gen-ff2gba-data.mjs <Dawn of Souls ROM (.gba)>
//
// From the ROM itself (never commit it): Final Fantasy II's item names are a table of u32 pointers at 0x1A3E84, one
// per item id as the save stores it (Shift-JIS with full-width ASCII, 0x87 xx is an icon). Spells are the spell books:
// spell id n is the book at item id 0x97 + n, without " Tome".

import { readFileSync, writeFileSync } from 'node:fs';

const romPath = process.argv[2];
if (!romPath) {
  console.error('usage: node scripts/gen-ff2gba-data.mjs <rom.gba>');
  process.exit(1);
}
const rom = readFileSync(romPath);
if (rom.toString('latin1', 0xac, 0xb0) !== 'BFFE') throw new Error('not Final Fantasy I & II: Dawn of Souls (US)');

const sjis = new TextDecoder('shift_jis');
function text(at) {
  const bytes = [];
  for (let i = at; rom[i]; i++) {
    const lead = (rom[i] >= 0x81 && rom[i] <= 0x9f) || (rom[i] >= 0xe0 && rom[i] <= 0xef);
    if (rom[i] === 0x87) { i++; continue; } // an icon
    bytes.push(rom[i]);
    if (lead) bytes.push(rom[++i]);
  }
  return sjis.decode(Uint8Array.from(bytes))
    .replace(/[！-～]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/　/g, ' ').replace(/’/g, "'").replace(/−/g, '-').trim();
}

const ITEM_COUNT = 0xc4;
const ITEMS = Array.from({ length: ITEM_COUNT }, (_, i) => text(rom.readUInt32LE(0x1a3e84 + i * 4) - 0x08000000));
if (ITEMS[0x10] !== 'Potion' || ITEMS[0x60] !== 'Masamune' || ITEMS[0x98] !== 'Fire Tome' || ITEMS[0xbf] !== 'Ultima Tome') {
  throw new Error('unexpected item names: the table moved');
}
const SPELLS = ITEMS.slice(0x98, 0xc0).map((n) => n.replace(/ Tome$/, ''));

const list = (a) => `[\n${a.map((s) => `  ${JSON.stringify(s)},`).join('\n')}\n]`;
const out = `// Generated by scripts/gen-ff2gba-data.mjs from the game's ROM. Do not edit by hand.
// Final Fantasy II (Dawn of Souls, GBA, US) names by save id.

/** Every item by the id the save uses (0-0xC3): key items 0x01-0x0E, items 0x10-0x2E, "Hands" (an empty hand) 0x30,
 * shields 0x31-0x39, weapons 0x3A-0x6F, helmets 0x70-0x79, armor 0x7A-0x8D, gloves and armlets 0x8E-0x97, spell
 * books 0x98-0xBF. */
export const ITEMS: readonly string[] = ${list(ITEMS)};
/** Spells, id 1-40 (the order of the spell books). */
export const SPELLS: readonly string[] = ${list(SPELLS)};
`;
writeFileSync(new URL('../src/core/ff2gba/tables.ts', import.meta.url), out);
console.log('wrote src/core/ff2gba/tables.ts');
