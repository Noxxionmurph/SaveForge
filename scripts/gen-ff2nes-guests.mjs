// Generates src/core/ff2nes/guests.ts (what each guest starts with when they join, for Final Fantasy II on the Famicom
// with Neo Demiforce's English patch) straight from the game. Run only when you want to regenerate it:
//
//   node scripts/gen-ff2nes-guests.mjs "<path to a Final Fantasy II (Japan) ROM with the English patch 1.0>.nes"
//
// Never commit the ROM. When someone joins the heroes, the game (00/9C0C) takes that guest's 0x76-byte record from a
// table of pointers at 00/9C45 (Minwu, Josef, Gordon, Leila, Ricard, Leon) and copies bytes 0x00-0x3F over the fourth
// character record ($61C0) and bytes 0x40-0x75 over the first 0x36 bytes of its second part ($62C0: skill and spell
// levels, then the byte whose top bit says the place is empty). Leon's record has no name: the game copies in the one
// typed for him at the start, kept at $6276.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const path = process.argv[2] && resolve(process.argv[2]);
if (!path) { console.error('Usage: node scripts/gen-ff2nes-guests.mjs <Final Fantasy II ROM, English patch>.nes'); process.exit(1); }
const rom = readFileSync(path);
if (rom.length !== 0x40010 || rom.readUInt32BE(0) !== 0x4e45531a) throw new Error('Not a 256 KB iNES ROM');

const bank0 = (addr) => 0x10 + (addr - 0x8000);
const RECORD = 0x76;
const GUESTS = ['Minwu', 'Josef', 'Gordon', 'Leila', 'Ricard', 'Leon'];
const records = GUESTS.map((name, k) => {
  const at = bank0(rom.readUInt16LE(bank0(0x9c45) + k * 2));
  const r = [...rom.subarray(at, at + RECORD)];
  if ((r[0] & 0x0f) !== 3 + k || r[0x75] & 0x80) throw new Error(`${name}'s record isn't where it should be: is this the right ROM?`);
  return r;
});
// Josef's name in the patch's letters (J o s e f, padded).
if (records[1].slice(2, 8).join() !== [0x93, 0xb2, 0xb6, 0xa8, 0xa9, 0xff].join()) throw new Error('Not the English patch: Josef is not called Josef');

const hex = (r) => r.map((b) => b.toString(16).padStart(2, '0')).join('');
const out = `// Generated by scripts/gen-ff2nes-guests.mjs from the game itself (English fan translation 1.0). Do not edit by hand.
// Final Fantasy II (Famicom): what the game writes into the fourth character record when each guest joins.

/** Minwu, Josef, Gordon, Leila, Ricard and Leon (character ids 3-8), 0x76 bytes each in hex: bytes 0x00-0x3F are the
 * record, 0x40-0x75 the start of its second part. Leon's name is blank: the game copies in the one typed at the start. */
export const GUEST_RECORDS: readonly string[] = [
${records.map((r) => `  '${hex(r)}',`).join('\n')}
];
`;
writeFileSync(new URL('../src/core/ff2nes/guests.ts', import.meta.url), out);
console.log('wrote src/core/ff2nes/guests.ts');
