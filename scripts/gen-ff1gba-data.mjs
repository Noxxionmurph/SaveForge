// Generates src/core/ff1gba/tables.ts for Final Fantasy I & II: Dawn of Souls (GBA, US, game code BFFE).
//
//   node scripts/gen-ff1gba-data.mjs <Dawn of Souls ROM (.gba)>
//
// Everything comes from the ROM itself (never commit it):
// - Names: the item table at 0x19E650 is 651 pointers in threes (short name, menu name, description), grouped as
//   blank, 36 key items, blank, 43 items, blank, 64 weapons, blank, 70 armor; spells are pointer pairs at 0x1A1650
//   (name, description), 1-32 white and 33-64 black. Text is Shift-JIS with full-width ASCII, and 0x87 xx is an icon.
// - Who can equip what: weapon records (28 bytes, 0x19F358) and armor records (28 bytes, 0x19FA74) hold the base
//   classes that can equip at +2 (bit = class 0-5) and the promoted ones at +3 (bit = class 6-11), the same layout as
//   the PSP remake. Spell learning: [base, promoted] byte pairs per spell at 0x1A20C2.
// - The armor list runs body (1-27), shield (28-41), helmet (42-57), gloves (58-70); the shop and menu sort it the same
//   way, and every piece worn in the real saves we have fits.
// Cross-checked against two real saves: every character's gear and spells are allowed by these tables.

import { readFileSync, writeFileSync } from 'node:fs';

const romPath = process.argv[2];
if (!romPath) {
  console.error('usage: node scripts/gen-ff1gba-data.mjs <rom.gba>');
  process.exit(1);
}
const rom = readFileSync(romPath);
if (rom.toString('latin1', 0xac, 0xb0) !== 'BFFE') throw new Error('not Final Fantasy I & II: Dawn of Souls (US)');

const sjis = new TextDecoder('shift_jis');
const ptr = (at) => rom.readUInt32LE(at) - 0x08000000;
function text(at) {
  const bytes = [];
  for (let i = at; rom[i]; i++) {
    const lead = (rom[i] >= 0x81 && rom[i] <= 0x9f) || (rom[i] >= 0xe0 && rom[i] <= 0xef);
    if (rom[i] === 0x87) { i++; continue; } // an icon
    bytes.push(rom[i]);
    if (lead) bytes.push(rom[++i]);
  }
  return sjis.decode(Uint8Array.from(bytes))
    .replace(/[！-～]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/　/g, ' ').replace(/’/g, "'").trim();
}

const ITEM_TABLE = 0x19e650;
const items = (first, count) => Array.from({ length: count }, (_, i) => text(ptr(ITEM_TABLE + (first + i) * 12)));
const KEY_ITEMS = items(1, 36);
const CONSUMABLES = items(38, 43);
const WEAPONS = items(82, 64);
const ARMOR = items(147, 70);
const SPELLS = Array.from({ length: 64 }, (_, i) => text(ptr(0x1a1650 + (i + 1) * 8)));
for (const [name, list] of Object.entries({ KEY_ITEMS, CONSUMABLES, WEAPONS, ARMOR, SPELLS })) {
  if (list.some((s) => !s)) throw new Error(`${name}: a blank name, so the table moved`);
}
if (CONSUMABLES[0] !== 'Potion' || WEAPONS[0] !== 'Nunchaku' || ARMOR[0] !== 'Clothes' || SPELLS[0] !== 'Cure' || KEY_ITEMS[0] !== 'Lute') {
  throw new Error('unexpected first names');
}

const jobs = (base, i) => rom[base + i * 28 + 2] | (rom[base + i * 28 + 3] << 6);
const WEAPON_JOBS = WEAPONS.map((_, i) => jobs(0x19f358, i));
const ARMOR_JOBS = ARMOR.map((_, i) => jobs(0x19fa74, i));
const SPELL_JOBS = SPELLS.map((_, i) => rom[0x1a20c2 + i * 2] | (rom[0x1a20c2 + i * 2 + 1] << 6));
// The save's gear order after the weapon: 0 shield, 1 helmet, 2 body, 3 gloves.
const ARMOR_SLOT = ARMOR.map((_, i) => (i < 27 ? 2 : i < 41 ? 0 : i < 57 ? 1 : 3));

const list = (a) => `[\n${a.map((s) => `  ${JSON.stringify(s)},`).join('\n')}\n]`;
const nums = (a) => `[${a.join(',')}]`;
const out = `// Generated by scripts/gen-ff1gba-data.mjs from the game's ROM. Do not edit by hand.
// Final Fantasy I (Dawn of Souls, GBA, US) names by save id, and the game's equip and magic tables.

/** Consumable items, id 1-43. */
export const CONSUMABLES: readonly string[] = ${list(CONSUMABLES)};
/** Weapons, id 1-64. */
export const WEAPONS: readonly string[] = ${list(WEAPONS)};
/** Armor, id 1-70. */
export const ARMOR: readonly string[] = ${list(ARMOR)};
/** Key items, id 1-36, in the order of the Key Items menu. */
export const KEY_ITEMS: readonly string[] = ${list(KEY_ITEMS)};
/** Spells, id 1-64: 1-32 white, 33-64 black, four per spell level. */
export const SPELLS: readonly string[] = ${list(SPELLS)};
/** Classes that can equip each weapon / armor / learn each spell: bit n = class n (0-11). */
export const WEAPON_JOBS: readonly number[] = ${nums(WEAPON_JOBS)};
export const ARMOR_JOBS: readonly number[] = ${nums(ARMOR_JOBS)};
export const SPELL_JOBS: readonly number[] = ${nums(SPELL_JOBS)};
/** The slot each armor goes in: 0 shield, 1 helmet, 2 body, 3 gloves (the order a character's gear is saved in). */
export const ARMOR_SLOT: readonly number[] = ${nums(ARMOR_SLOT)};
`;
writeFileSync(new URL('../src/core/ff1gba/tables.ts', import.meta.url), out);
console.log('wrote src/core/ff1gba/tables.ts');
